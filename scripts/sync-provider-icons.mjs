#!/usr/bin/env node
// sync-provider-icons.mjs — vendor opencode's monochrome provider icons (R3-1141).
//
// Fetches packages/ui/src/assets/icons/provider/*.svg from sst/opencode at a PINNED
// commit (no runtime fetch — the CSP allows no external image host; a refresh's diff is
// reviewable), optimizes each with svgo, enforces monochrome (every fill/stroke becomes
// currentColor except `none`), and writes src/providerIcons/sprite.generated.ts: a
// `<symbol id="pi-<id>">` sprite string plus PROVIDER_ICON_IDS, keyed by the models.dev
// provider id (the filename stem — the same key as the catalogue's modelsDevId).
//
// Run: node scripts/sync-provider-icons.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { optimize } from 'svgo';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PIN = '0dcedc199c83c88ef206b4d89351f4a0e4a9a61d'; // sst/opencode, 2026-08-10
const API = `https://api.github.com/repos/sst/opencode/contents/packages/ui/src/assets/icons/provider?ref=${PIN}`;
const RAW = `https://raw.githubusercontent.com/sst/opencode/${PIN}/packages/ui/src/assets/icons/provider`;

const listing = await fetch(API, { headers: { 'user-agent': 'immediately-run-icon-sync' } }).then((r) => {
  if (!r.ok) throw new Error(`listing: HTTP ${r.status}`);
  return r.json();
});
const files = listing
  .filter((f) => f.name.endsWith('.svg'))
  .map((f) => f.name)
  .sort();
if (files.length < 50) throw new Error(`only ${files.length} icons listed — refusing to write a partial sprite`);

const symbols = [];
for (const name of files) {
  const id = name.replace(/\.svg$/, '');
  const raw = await fetch(`${RAW}/${name}`).then((r) => {
    if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
    return r.text();
  });
  const { data } = optimize(raw, {
    multipass: true,
    plugins: [
      // Style-carried paint FIRST (convertStyleToAttrs): svgo's convertColors rewrites
      // only fill=/stroke= ATTRIBUTES, and an inline style beats a presentation
      // attribute in the cascade — zenmux shipped `style="fill:#f5f5f5;…"` and would
      // have rendered brand-colored under a "monochrome" claim (review round 1).
      'convertStyleToAttrs',
      'preset-default',
      // Monochrome by construction (the Architecture's "enforced by the generator"):
      // every paint server becomes currentColor except an explicit none.
      {
        name: 'convertColors',
        params: { currentColor: true },
      },
    ],
  });
  // Post-check (the test re-asserts over the generated file, but fail here so a bad
  // upstream icon never reaches the tree): no hex/rgb fill or stroke survives — in
  // attributes OR in a style declaration.
  const paints = [
    ...[...data.matchAll(/(?:fill|stroke)="([^"]*)"/g)].map((m) => m[1]),
    ...[...data.matchAll(/style="([^"]*)"/g)].flatMap((m) =>
      [...m[1].matchAll(/(?:^|;)\s*(?:fill|stroke)\s*:\s*([^;]+)/g)].map((d) => d[1].trim()),
    ),
  ];
  for (const p of paints) {
    if (p !== 'currentColor' && p !== 'none') throw new Error(`${name}: non-monochrome paint "${p}"`);
  }
  const viewBox = data.match(/viewBox="([^"]*)"/)?.[1] ?? '0 0 24 24';
  const inner = data.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  symbols.push(`<symbol id="pi-${id}" viewBox="${viewBox}">${inner}</symbol>`);
}

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join('')}</svg>`;
const out = `// GENERATED by scripts/sync-provider-icons.mjs from sst/opencode@${PIN.slice(0, 12)}
// (packages/ui/src/assets/icons/provider, MIT — see NOTICE.md). Regenerate, never edit.
/** The one sprite string, injected once per document by ProviderIcon. Typed \`string\`,
 *  not the literal — the api snapshot pins the SHAPE, and a refresh must not read as a
 *  breaking change (the sprite's content is this repo's own generated artifact). */
export const PROVIDER_ICON_SPRITE: string = ${JSON.stringify(sprite)};

/** The models.dev provider ids with an icon in the sprite (the \`pi-<id>\` symbol set). */
export const PROVIDER_ICON_IDS: readonly string[] = ${JSON.stringify(
  files.map((f) => f.replace(/\.svg$/, '')),
  null,
  2,
)};
`;
writeFileSync(join(ROOT, 'src/providerIcons/sprite.generated.ts'), out);
console.log(`✓ ${symbols.length} icons, sprite ${(sprite.length / 1024).toFixed(0)} KB raw`);
